"""
Write a Windows batch file that runs the rebuilt SFINCS models one after another.

Each case runs inside its own folder (models/rebuild/<variant>/<case>/), writes its terminal
output to sfincs_log.txt there, and is skipped if sfincs_map.nc already exists, so the batch
file can be stopped and restarted. A line per case is appended to run_status.txt next to the
batch file.

Usage (from the repository root):
    python scripts/sfincs_rebuild/write_batch.py
    python scripts/sfincs_rebuild/write_batch.py --variants subgrid_200m --splits test_unseen_rainfall
    python scripts/sfincs_rebuild/write_batch.py --sfincs-exe D:/sfincs/sfincs.exe --threads 4
"""

from pathlib import Path
import argparse

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_EXE = Path(r"c:\Users\leijnse\executables\SFINCS_2025_02_release\SFINCS_v2.3.0_mt_Faber_release_exe\sfincs.exe")
VARIANTS = ("regular_100m", "subgrid_200m", "subgrid_400m")


def write_batch_file(case_table, model_root, sfincs_exe, out_bat, variants=VARIANTS, threads=None):
    """Write one .bat file that runs every case in case_table for every variant."""

    model_root = Path(model_root).resolve()
    out_bat = Path(out_bat).resolve()
    status_file = out_bat.with_name("run_status.txt")

    lines = [
        "@echo off",
        "rem Generated by scripts/sfincs_rebuild/write_batch.py - runs SFINCS for the rebuilt test-case models.",
        "rem Cases with an existing sfincs_map.nc are skipped; delete it to rerun a case.",
        "setlocal",
        f'set "SFINCS_EXE={sfincs_exe}"',
        f'set "STATUS={status_file}"',
    ]
    if threads is not None:
        lines.append(f"set OMP_NUM_THREADS={threads}")  # Threads used by the multithreaded (mt) executable.
    lines += [
        'if not exist "%SFINCS_EXE%" (echo SFINCS executable not found: %SFINCS_EXE% & exit /b 1)',
        "",
    ]

    n_cases = 0
    missing = []
    for variant in variants:
        lines.append(f"rem ===== {variant} =====")
        for _, case_row in case_table.iterrows():
            case_dir = model_root / variant / case_row["case_name"]
            if not (case_dir / "sfincs.inp").exists():
                missing.append(str(case_dir))
                continue
            n_cases += 1
            label = f"{variant}/{case_row['case_name']}"
            lines += [
                f'if exist "{case_dir}\\sfincs_map.nc" (',
                f"    echo [skip] {label}",
                ") else (",
                f"    echo [run ] {label}",
                f'    pushd "{case_dir}"',
                '    call "%SFINCS_EXE%" > sfincs_log.txt 2>&1',  # call: also returns if the exe is a wrapper .bat/.cmd.
                f'    if errorlevel 1 (echo FAILED {label}>> "%STATUS%") else (echo OK {label}>> "%STATUS%")',
                "    popd",
                ")",
            ]
        lines.append("")

    lines += ["echo Done. See %STATUS% for per-case results.", "endlocal", ""]

    out_bat.parent.mkdir(parents=True, exist_ok=True)
    out_bat.write_text("\n".join(lines), encoding="ascii", newline="\r\n")  # CRLF line endings for cmd.exe.

    return out_bat, n_cases, missing


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sfincs-exe", type=Path, default=DEFAULT_EXE, help="Path to sfincs.exe")
    parser.add_argument("--variants", nargs="+", default=list(VARIANTS), choices=VARIANTS)
    parser.add_argument("--splits", nargs="+", default=None, help="Only these splits (default: all three)")
    parser.add_argument("--threads", type=int, default=None, help="Set OMP_NUM_THREADS in the batch file")
    parser.add_argument("--model-root", type=Path, default=PROJECT_ROOT / "models" / "rebuild")
    parser.add_argument("--case-table", type=Path, default=PROJECT_ROOT / "outputs" / "rebuild" / "case_table.csv")
    parser.add_argument("--out", type=Path, default=None, help="Batch file path (default: <model-root>/run_sfincs.bat)")
    args = parser.parse_args()

    case_table = pd.read_csv(args.case_table)
    if args.splits:
        case_table = case_table[case_table["split"].isin(args.splits)]

    out_bat = args.out or args.model_root / "run_sfincs.bat"
    out_bat, n_cases, missing = write_batch_file(
        case_table, args.model_root, args.sfincs_exe, out_bat, args.variants, args.threads
    )

    if not args.sfincs_exe.exists():
        print(f"Warning: SFINCS executable not found: {args.sfincs_exe}")
    if missing:
        print(f"Warning: {len(missing)} case folders have no sfincs.inp and were left out (build them first).")
    print(f"Wrote {out_bat} with {n_cases} runs.")


if __name__ == "__main__":
    main()
