"""
Write a Linux shell script that runs the rebuilt SFINCS models on the H7 cluster with Apptainer.

Linux counterpart of write_batch.py. The SFINCS Docker image is pulled once into a .sif file in the
Apptainer folder (models/rebuild/Apptainer_CPU_H7/ on the P: drive, /p/... on H7) and reused by later
runs. Each case runs inside its own folder (<linux-root>/<variant>/<case>/), writes its terminal output
to sfincs_log.txt there. Existing output (e.g. copied Windows results) is overwritten by default; with
--skip-existing, or SKIP_EXISTING=1 at submit time, cases that already have sfincs_map.nc are skipped so
an interrupted job can be restarted. A line per case is appended to run_status.txt next to the script.

The script works both with plain bash and as a Slurm job (sbatch); the #SBATCH lines are ignored by bash.
Which cases are included is decided from the local model folders (--model-root), which should hold the
same <variant>/<case> layout as the folder on H7.

Usage (from the repository root):
    python scripts/sfincs_rebuild/write_sh_h7.py
    python scripts/sfincs_rebuild/write_sh_h7.py --variants subgrid_200m --splits test_unseen_rainfall
    python scripts/sfincs_rebuild/write_sh_h7.py --partition 16vcpu --cpus 16 --time 1-00:00:00

Then on H7:
    sbatch /p/11202255-sfincs/Projects/SFINCS_mSWE-GNN_SU/models/rebuild/Apptainer_CPU_H7/run_sfincs_h7.sh
"""

from pathlib import Path, PureWindowsPath
import argparse

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_IMAGE = "deltares/sfincs-cpu:sfincs-v2.3.0-mt-Faber-Release"
DEFAULT_WIN_ROOT = Path(r"p:\11202255-sfincs\Projects\SFINCS_mSWE-GNN_SU\models\rebuild\Apptainer_CPU_H7")
VARIANTS = ("regular_100m", "subgrid_200m", "subgrid_400m")


def to_linux_path(win_path):
    """Map a P: drive path to its H7 mount (p:\\a\\b -> /p/a/b); other paths are returned as posix."""

    win_path = PureWindowsPath(win_path)
    if win_path.drive:
        return "/" + win_path.drive.rstrip(":").lower() + "/" + "/".join(win_path.parts[1:])
    return win_path.as_posix()


def write_sh_file(case_table, model_root, linux_root, out_sh, image=DEFAULT_IMAGE, variants=VARIANTS,
                  threads=None, partition=None, cpus=None, time=None, job_name="sfincs_rebuild",
                  skip_existing=False):
    """Write one .sh file that runs every case in case_table for every variant via Apptainer."""

    model_root = Path(model_root).resolve()
    out_sh = Path(out_sh)
    sif_name = image.split("/")[-1].replace(":", "_") + ".sif"

    lines = ["#!/bin/bash"]
    lines.append(f"#SBATCH --job-name={job_name}")
    lines.append(f"#SBATCH --output={linux_root}/slurm_%j.out")
    if partition:
        lines.append(f"#SBATCH --partition={partition}")
    if cpus:
        lines += ["#SBATCH --nodes=1", "#SBATCH --ntasks=1", f"#SBATCH --cpus-per-task={cpus}"]
    if time:
        lines.append(f"#SBATCH --time={time}")
    lines += [
        "# Generated by scripts/sfincs_rebuild/write_sh_h7.py - runs SFINCS (Apptainer) for the rebuilt test-case models.",
        "# Existing output is overwritten unless SKIP_EXISTING=1 (then cases with sfincs_map.nc are skipped).",
        "",
        f'SKIP_EXISTING="${{SKIP_EXISTING:-{int(skip_existing)}}}"',
        f'ROOT="{linux_root}"',
        f'IMAGE="docker://{image}"',
        f'SIF="$ROOT/{sif_name}"',
        'STATUS="$ROOT/run_status.txt"',
        'export APPTAINER_CACHEDIR="$ROOT/.apptainer_cache"  # Keep the pull cache out of the home quota.',
    ]
    if threads is not None:
        lines.append(f"export OMP_NUM_THREADS={threads}")  # Threads used by the multithreaded (mt) executable.
    else:
        lines.append('export OMP_NUM_THREADS="${SLURM_CPUS_PER_TASK:-${OMP_NUM_THREADS:-1}}"')
    lines += [
        "",
        "if ! command -v apptainer > /dev/null 2>&1; then module load apptainer 2> /dev/null; fi",
        'command -v apptainer > /dev/null 2>&1 || { echo "apptainer not found"; exit 1; }',
        "",
        "# Pull the image once; later runs reuse the .sif file.",
        'if [ ! -f "$SIF" ]; then',
        '    echo "Pulling $IMAGE to $SIF"',
        '    apptainer pull "$SIF" "$IMAGE" || { echo "apptainer pull failed"; exit 1; }',
        "fi",
        "",
        "run_case() {",
        '    local label="$1" case_dir="$ROOT/$1"',
        '    if [ ! -f "$case_dir/sfincs.inp" ]; then',
        '        echo "[miss] $label"',
        '        echo "MISSING $label" >> "$STATUS"',
        '    elif [ "$SKIP_EXISTING" = 1 ] && [ -f "$case_dir/sfincs_map.nc" ]; then',
        '        echo "[skip] $label"',
        "    else",
        '        echo "[run ] $label"',
        # The image runs sfincs in /data, so the case folder is mounted there.
        '        if apptainer run --bind "$case_dir:/data" --pwd /data "$SIF" > "$case_dir/sfincs_log.txt" 2>&1; then',
        '            echo "OK $label" >> "$STATUS"',
        "        else",
        '            echo "FAILED $label" >> "$STATUS"',
        "        fi",
        "    fi",
        "}",
        "",
    ]

    n_cases = 0
    missing = []
    for variant in variants:
        lines.append(f"# ===== {variant} =====")
        for _, case_row in case_table.iterrows():
            if not (model_root / variant / case_row["case_name"] / "sfincs.inp").exists():
                missing.append(str(model_root / variant / case_row["case_name"]))
                continue
            n_cases += 1
            lines.append(f"run_case {variant}/{case_row['case_name']}")
        lines.append("")

    lines += ['echo "Done. See $STATUS for per-case results."', ""]

    out_sh.parent.mkdir(parents=True, exist_ok=True)
    out_sh.write_text("\n".join(lines), encoding="ascii", newline="\n")  # LF line endings for bash.

    return out_sh, n_cases, missing


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--image", default=DEFAULT_IMAGE, help="Docker image to run with Apptainer")
    parser.add_argument("--variants", nargs="+", default=list(VARIANTS), choices=VARIANTS)
    parser.add_argument("--splits", nargs="+", default=None, help="Only these splits (default: all three)")
    parser.add_argument("--threads", type=int, default=None,
                        help="Set OMP_NUM_THREADS (default: Slurm --cpus-per-task, else 1)")
    parser.add_argument("--partition", default=None, help="Slurm partition (#SBATCH --partition)")
    parser.add_argument("--cpus", type=int, default=None, help="Slurm --cpus-per-task")
    parser.add_argument("--time", default=None, help="Slurm wall time, e.g. 1-00:00:00")
    parser.add_argument("--skip-existing", action="store_true",
                        help="Skip cases that already have sfincs_map.nc (default: rerun and overwrite)")
    parser.add_argument("--win-root", type=Path, default=DEFAULT_WIN_ROOT,
                        help="Apptainer folder as seen from Windows; the script and .sif are written here")
    parser.add_argument("--linux-root", default=None,
                        help="Same folder as seen from H7 (default: --win-root with p:\\ mapped to /p/)")
    parser.add_argument("--model-root", type=Path, default=None,
                        help="Local folder with <variant>/<case> models used to select cases (default: --win-root)")
    parser.add_argument("--case-table", type=Path, default=PROJECT_ROOT / "outputs" / "rebuild" / "case_table.csv")
    parser.add_argument("--out", type=Path, default=None, help="Shell script path (default: <win-root>/run_sfincs_h7.sh)")
    args = parser.parse_args()

    case_table = pd.read_csv(args.case_table)
    if args.splits:
        case_table = case_table[case_table["split"].isin(args.splits)]

    linux_root = args.linux_root or to_linux_path(args.win_root)
    model_root = args.model_root or args.win_root
    out_sh = args.out or args.win_root / "run_sfincs_h7.sh"
    out_sh, n_cases, missing = write_sh_file(
        case_table, model_root, linux_root, out_sh, args.image, args.variants,
        args.threads, args.partition, args.cpus, args.time, skip_existing=args.skip_existing,
    )

    if missing:
        print(f"Warning: {len(missing)} case folders in {model_root} have no sfincs.inp and were left out "
              "(copy the built models there first).")
    print(f"Wrote {out_sh} with {n_cases} runs (H7 root: {linux_root}).")


if __name__ == "__main__":
    main()
